"""Render the localisation config into the files the system actually reads.

Run at boot by rave-localization.service and again whenever the setting
changes, so a reboot always lands in the configured state regardless of what
the API did.

Owned paths, none of which any package also writes:

    /run/rave-menu/weston.ini        compositor config (tmpfs, rebuilt each boot)
    /etc/default/rave-localization   LANG + chromium --lang for weston.service
    /etc/locale.conf                 system locale
    /etc/vconsole.conf               VT keymap

/etc/xdg/weston/rave-menu.ini is deliberately NOT written here. It stays as
the package-owned static fallback that the weston drop-in copies into /run if
this script ever fails to produce one -- Weston exits 1 on a missing config,
and with Restart=on-failure that is a dead display, not a degraded one.
"""

import argparse
import configparser
import json
import subprocess
import sys
import time
from pathlib import Path

import localization as loc

MINIMAL_TEMPLATE = """[core]
idle-time=0
shell=kiosk-shell.so

[autolaunch]
path=/usr/bin/rave-cog-launch.sh
watch=true
"""

REQUIRED_SECTIONS = ("core", "autolaunch")


def log(message: str) -> None:
    print(f"apply_localization: {message}", file=sys.stderr)


def _base_template() -> str:
    """Prefer the shipped template, then the static fallback, then built-in."""
    for candidate in (loc.WESTON_TEMPLATE, loc.WESTON_FALLBACK):
        try:
            return candidate.read_text(encoding="utf-8")
        except OSError:
            continue
    log("no weston template found, using built-in minimal config")
    return MINIMAL_TEMPLATE


def _assert_usable(content: str) -> None:
    """A config missing these sections boots to a blank screen, not an error."""
    parser = configparser.ConfigParser()
    parser.read_string(content)
    for section in REQUIRED_SECTIONS:
        if not parser.has_section(section):
            raise ValueError(f"rendered weston config lost [{section}]")


def write_weston_config(cfg: dict) -> bool:
    """Render the compositor config, falling back rather than leaving none."""
    try:
        content = loc.render_weston_ini(_base_template(), cfg)
        _assert_usable(content)
        loc.write_atomic(loc.WESTON_RUNTIME, content)
        return True
    except Exception as exc:  # noqa: BLE001 - must never propagate to boot
        log(f"ERROR rendering weston config: {exc!r}")
        try:
            loc.write_atomic(loc.WESTON_RUNTIME,
                             loc.WESTON_FALLBACK.read_text(encoding="utf-8"))
            log("installed static fallback weston config")
        except OSError as fallback_exc:
            log(f"ERROR installing fallback config: {fallback_exc!r}")
        return False


def write_system_files(cfg: dict) -> None:
    loc.write_atomic(loc.ENV_FILE, loc.render_env_file(cfg))
    loc.write_atomic(
        loc.LOCALE_CONF,
        f"# Generated by rave-menu. Edits are overwritten.\n"
        f"LANG={cfg['language']}\n")
    loc.write_atomic(
        loc.VCONSOLE_CONF,
        f"# Generated by rave-menu. Edits are overwritten.\n"
        f"KEYMAP={loc.console_keymap(cfg['keyboard']['layout'])}\n")


def load_vt_keymap(cfg: dict) -> None:
    """Best effort: the product's UI is the kiosk browser, not the VT."""
    keymap = loc.console_keymap(cfg["keyboard"]["layout"])
    try:
        proc = subprocess.run(["loadkeys", keymap], capture_output=True,
                              text=True, timeout=20, check=False)
        if proc.returncode != 0:
            log(f"loadkeys {keymap} returned {proc.returncode} (continuing)")
    except (OSError, subprocess.SubprocessError) as exc:
        log(f"loadkeys unavailable: {exc!r} (continuing)")


def mark_verify_pending() -> None:
    """Ask the menu to land on the localisation page after the kiosk restarts.

    Written only on the API path. Doing this at boot would redirect every boot
    into the settings page. /run is tmpfs, so it cannot persist.
    """
    try:
        loc.write_atomic(loc.VERIFY_FLAG,
                         json.dumps({"at": time.time()}) + "\n")
    except OSError as exc:
        log(f"could not write verify flag: {exc!r}")


def apply_all(cfg: dict, from_api: bool = False) -> bool:
    ok = write_weston_config(cfg)
    try:
        write_system_files(cfg)
    except OSError as exc:
        log(f"ERROR writing system files: {exc!r}")
        ok = False
    load_vt_keymap(cfg)
    if from_api:
        mark_verify_pending()
    log(f"applied layout={cfg['keyboard']['layout']} "
        f"variant={cfg['keyboard']['variant'] or '-'} "
        f"language={cfg['language']} ok={ok}")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--boot", action="store_true",
                      help="boot-time apply (default)")
    mode.add_argument("--from-api", action="store_true",
                      help="apply after a user change; sets the verify flag")
    args = parser.parse_args()

    cfg = loc.load_config()
    return 0 if apply_all(cfg, from_api=args.from_api) else 1


if __name__ == "__main__":
    sys.exit(main())
